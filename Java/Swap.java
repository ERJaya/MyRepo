public class Swap {
    //Swap 2 number using 3rd variable.
    public static void main(String[] args) {
        int a=45;
        int b=80;
        int temp;
        System.out.println("Before Swap the value of a=" +a+"b="+b);
        temp=a;
        a=b;
        b=temp;
        System.out.println("After Swap the value of a=" +a+"b="+b);
    }
    
}
